'use strict';
const assert=require('node:assert/strict');
const {TaskCenterCollector}=require('../desktop-sync/task-center.cjs');
const events=[],tabs=[],visited=[];
const frame={url:()=> 'https://mooc2-ans.chaoxing.com/visit/interaction',locator:()=>({count:async()=>6,nth:index=>({getAttribute:async()=>`https://mooc2-ans.chaoxing.com/mooc2-ans/mycourse/stu?courseId=${index+1}&clazzid=22`,textContent:async()=>`课程${index+1}`,click:async()=>{visited.push(index);tabs.push({url:()=>`https://mooc2-ans.chaoxing.com/mooc2-ans/mycourse/stu?courseId=${index+1}&clazzid=22`,locator:()=>({filter:()=>({first:()=>({waitFor:async()=>{}})})}),close:async()=>tabs.pop()})}})})};
const job=(n,course=6)=>({kind:'task_center',message_id:'inventory_'+n,title:'作业'+n,text:'说明'+n,course:'课程六',task_type:'assignment',url:`https://mooc1.chaoxing.com/mooc2/work/detail?courseId=${course}&classId=22&workId=${n}`});
(async()=>{
 const collector=new TaskCenterCollector({context:{pages:()=>[...tabs]},accepted:new Set(),isCurrent:()=>true,onMessage:()=>{},onStatus:()=>{},onInventory:event=>events.push(event)});
 collector.portal=async()=>frame;
 collector.list=async()=>({checked:0,captured:0,rejected:0});
 collector.requestRepair(['6|22|assignment|19']);
 await collector.sweep();
 assert.equal(visited[0],5,'a missing task course must be checked before the ordinary cursor');
 assert(events.some(e=>e.phase==='catalog'&&e.courses.length===6),'emit known course coverage even before lists succeed');
 const jobs=[job(1),job(2),job(3),job(4),job(5),job(19)];
 const listFrame={url:()=> 'https://mooc1.chaoxing.com/mooc2/work/list',waitForFunction:async()=>{},evaluate:async code=>typeof code==='string'?undefined:jobs,locator:()=>({count:async()=>jobs.length})};
 const tab={locator:()=>({filter:()=>({first:()=>({count:async()=>1,click:async()=>{}})})}),frames:()=>[listFrame]};
 const read=[],delivered=[];
 const target=new TaskCenterCollector({context:{},accepted:new Set(),isCurrent:()=>true,onMessage:j=>{events.push({phase:'delivery'});delivered.push(j)},onStatus:()=>{},onInventory:event=>events.push(event)});
 target.detail=async j=>{read.push(j.message_id);return {...j,detail_state:'read',_media_count:j.message_id==='inventory_19'?2:0}};
 target.requestRepair(['6|22|assignment|19']);
 await target.list(tab,'assignment','课程六',{courseId:'6',classId:'22'});
 assert.equal(read[0],'inventory_19','targeted missing detail has priority inside the five-detail budget');
 assert.equal(read.length,5);
 assert.equal(delivered.length,6,'a priority repair must preserve ordinary list intake');
 const first=events.findIndex(e=>e.phase==='section'&&!e.complete);
 const last=events.findIndex(e=>e.phase==='section'&&e.complete);
 assert(first>=0&&last>first,'publish expected tasks before delivery and verify the section only after delivery');
 assert.equal(events[last].jobs.length,6);
 assert.equal(events[last].jobs.find(j=>j.message_id==='inventory_19').detail_state,'read');
 assert.equal(delivered.find(j=>j.message_id==='inventory_19').media_pending_count,2,'per-task media gaps must survive delivery');
 assert(!('_media_count' in delivered[0]));
 visited.length=0;collector.repairs.clear();collector.cursor=0;
 collector.requestRepairSections(['5|22|exam']);
 await collector.sweep();assert.equal(visited[0],4,'a failed empty section must also be targetable');
 console.log('PASS: inventory manifests and bounded targeted repairs preserve ordinary intake');
})().catch(error=>{console.error(error);process.exitCode=1});
